export function validateTeam(nameOrCode) {
  if (!nameOrCode) return false;
  const target = nameOrCode.trim().toLowerCase();
  return REGISTERED_TEAMS.some(t => 
    t.name.toLowerCase() === target || t.code.toLowerCase() === target
  );
}

export function findTeamName(nameOrCode) {
  if (!nameOrCode) return nameOrCode;
  const target = nameOrCode.trim().toLowerCase();
  const found = REGISTERED_TEAMS.find(t => 
    t.name.toLowerCase() === target || t.code.toLowerCase() === target
  );
  return found ? found.name : nameOrCode;
}
